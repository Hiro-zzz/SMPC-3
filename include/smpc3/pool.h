/* SMPC3 :: pool.h -- пул инстансов виртуальной машины.
 *
 * Один скомпилированный модуль, N независимых инстансов. У каждого свои арены,
 * свой регистровый файл, своя рабочая память ядер и свой журнал диагностики.
 * Общего между ними — только сам модуль, а он неизменяем.
 *
 * Именно поэтому инстансы можно раскидать по потокам без единого мьютекса:
 * разделяемого изменяемого состояния просто нет. Единственная синхронизация во
 * всём пуле — атомарный счётчик выданных заданий.
 *
 * Аллокации происходят при подъёме пула и только там: на исполнении ни один
 * инстанс не берёт ни байта.
 */
#ifndef SMPC3_POOL_H
#define SMPC3_POOL_H

#include "smpc3/vm.h"

#define SMP_POOL_MAX_INSTANCES 1024u

/* Сколько памяти отводится журналу одного инстанса. Раньше журналом был
 * tmpfile(), то есть открытый дескриптор на инстанс, и пул не поднимался с 510
 * при заявленных 1024: CRT держит 512 файлов, минус stdin/stdout/stderr.
 *
 * Теперь это буфер, выделенный один раз при подъёме. Размер конечен, поэтому
 * поток вывода инстанса может в него не влезть — тогда журнал поднимает
 * truncated, и отчёт об этом прямо говорит. Тихо терять хвост нельзя. */
#define SMP_POOL_LOG_BYTES (16u * 1024u)

typedef struct SmpVMPool {
    const SmpModule *mod;

    SmpVM      *inst;        /* n_inst инстансов                             */
    SmpDiagCtx *diag;        /* по одному контексту на инстанс               */
    SmpLog     *log;         /* и по журналу: иначе вывод потоков перемешается */
    char       *logmem;      /* единый блок под все журналы                  */
    SmpStatus  *status;      /* чем закончился каждый                        */
    uint32_t    n_inst;
    uint32_t    n_threads;

    volatile int32_t cursor; /* выданные задания; единственная синхронизация  */

    uint64_t    n_executed;  /* суммарно инструкций                          */
    uint32_t    n_failed;
    double      seconds;     /* сколько заняло последнее smp_vm_pool_run     */
} SmpVMPool;

/* n_threads == 0 — взять по числу логических процессоров. */
SmpStatus smp_vm_pool_init(SmpVMPool *p, const SmpModule *mod,
                           uint32_t n_inst, uint32_t n_threads);

/* Исполняет все инстансы. Возвращает SMP_OK, только если не упал ни один. */
SmpStatus smp_vm_pool_run(SmpVMPool *p);

void      smp_vm_pool_release(SmpVMPool *p);

/* Печатает журналы упавших инстансов — по очереди, с указанием номера.
 * Во время исполнения их никто не печатает именно ради этого: диагностика от
 * шестнадцати потоков вперемешку нечитаема. */
void      smp_vm_pool_report(FILE *out, SmpVMPool *p);

/* Указатель на данные именованного тензора внутри конкретного инстанса.
 * Через него хост кладёт входные данные и забирает результат. */
void     *smp_vm_pool_tensor(const SmpVMPool *p, uint32_t inst,
                             const char *name, const SmpTensor **desc);

#endif /* SMPC3_POOL_H */
