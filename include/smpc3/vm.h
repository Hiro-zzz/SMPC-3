/* SMPC3 :: vm.h -- Direct Threading VM.
 *
 * Диспетчеризация идёт через goto *dispatch[op] на прямых метках: у switch на
 * горячем цикле один общий переход, который предсказатель ветвлений угадать
 * не может, а здесь у каждой инструкции свой — история переходов работает.
 * Там, где computed goto недоступен, собирается корректная switch-версия.
 *
 * Память: арены поднимаются один раз в smp_vm_init по размерам из модуля.
 * За время исполнения не выделяется ни байта.
 */
#ifndef SMPC3_VM_H
#define SMPC3_VM_H

#include "smpc3/arena.h"
#include "smpc3/bytecode.h"
#include "smpc3/diag.h"
#include "smpc3/kernels.h"

/* --- Привязка тензора к файлу ----------------------------------------------
 *
 * Единственный способ передать модулю данные снаружи и забрать результат.
 *
 * Ключ — имя тензора в исходнике, а не путь. Путь живёт в командной строке;
 * программа знает только «вход Q» и «выход S». Иначе имя файла пришлось бы
 * писать в .smpc, а строкового типа в языке нет, и заводить его ради этого
 * было бы нечестно.
 *
 * Файл сырой, без заголовка: объявление тензора в исходнике и есть схема,
 * заголовок дублировал бы её и однажды с ней разошёлся. Проверяется размер —
 * он обязан совпасть байт в байт. Тип элемента остаётся на совести автора,
 * ровно как [!no-alias]: f32:8 и f64:4 занимают одинаковые 32 байта, и
 * различить их по содержимому нечем. */
#define SMP_MAX_BINDS 32u

typedef struct SmpBind {
    const char *name;    /* имя тензора в исходнике */
    const char *path;
    bool        write;   /* true — выход (@store), false — вход (@load) */
} SmpBind;

/* --- Хранилище -------------------------------------------------------------
 *
 * Второй способ обмена с внешним миром — для хозяина, у которого файлов нет.
 * Ядро NablaOS держит рабочее пространство: объекты в памяти, которые
 * переживают программу. С хранилищем @load и @store работают с объектом того
 * же имени, что и тензор, — без привязок и без путей.
 *
 * В отличие от файла, объект хранилища помнит тип и форму, с которыми его
 * положили, и @load сверяет их, а не один размер: f32:8 и f64:4 здесь уже
 * различимы, и подсунуть одно вместо другого нельзя. */
typedef struct SmpStore {
    void *ctx;

    /* Есть ли объект: true и его тип с формой (dtype, rank, shape) в desc. */
    bool (*find) (void *ctx, const char *name, SmpTensor *desc);

    /* Содержимое объекта в dst. Тип и форма к этому моменту уже сверены. */
    void (*read) (void *ctx, const char *name, void *dst, uint64_t bytes);

    /* Положить плотный тензор под именем name, заменив прежний объект.
     * false — хранилищу не хватило места. */
    bool (*write)(void *ctx, const char *name, const SmpTensor *desc,
                  const void *src, uint64_t bytes);

    /* Объект по адресу, без копии — для @load в вид (sema.h, SmpSym.view).
     * Тип и форма к этому моменту сверены. NULL вместо функции — хранилище
     * так не умеет, и VM держит копию видов сама. Адрес живёт, пока объект
     * не заменили и не удалили: VM забывает его в начале каждого прогона,
     * берёт заново на каждом @load и отпускает после @store того же имени.
     * Писать по нему VM не станет. */
    const void *(*map)(void *ctx, const char *name);
} SmpStore;

/* Вид, загруженный по адресу: чем стал тензор name_id на этом прогоне. */
typedef struct SmpView {
    uint32_t       name_id;
    uint64_t       off;         /* смещение самого тензора в пространстве видов */
    uint64_t       bytes;
    const uint8_t *p;
} SmpView;

/* Регистр держит либо дескриптор тензора, либо скаляр. */
typedef struct SmpReg {
    bool      is_tensor;
    SmpTensor t;
    SmpConst  s;
    uint8_t   dtype;    /* тип скаляра */
} SmpReg;

typedef struct SmpVM {
    const SmpModule *mod;
    SmpDiagCtx      *diag;

    SmpArena  arenas[SMP_MAX_ARENAS];
    uint32_t  n_arenas;

    /* Регистровый файл лежит прямо в структуре: глобальный массив сделал бы
     * две VM в одном процессе неотличимыми друг от друга. */
    SmpReg    regs[SMP_MAX_REGS];
    uint32_t  n_regs;

    uint32_t  instance;        /* номер инстанса в пуле; вне пула ноль      */
    uint32_t  pc;              /* текущая инструкция — для дампа            */
    uint64_t  n_executed;
    uint32_t  entry_mxcsr;     /* состояние MXCSR до запуска                */
    uint8_t   cur_fp_flags;    /* какие fp-режимы сейчас в MXCSR            */
    bool      trapped;

    /* Была ли VM поднята. Без этого признака smp_vm_release на обнулённой
     * структуре записал бы в MXCSR ноль, то есть СНЯЛ БЫ МАСКИ всех
     * исключений FPU — и следующая же неточная операция с плавающей точкой
     * убила бы процесс аппаратной ловушкой в произвольном месте. */
    bool      live;

    /* Куда пишет @emit. Если задан out_log — в него, иначе в out; NULL там
     * означает stdout. Журнал нужен пулу: файл на инстанс упирался в лимит
     * открытых дескрипторов CRT. */
    FILE     *out;
    SmpLog   *out_log;

    /* Привязки тензоров к файлам. Принадлежат вызывающему и живут дольше VM:
     * пути приходят из argv и никуда не денутся. */
    const SmpBind *binds;
    uint32_t       n_binds;

    /* Хранилище вместо файлов; NULL — работают привязки. */
    const SmpStore *store;

    /* Виды. У хранилища с map — адреса объектов, живут один прогон. Иначе
     * — своя копия всего пространства видов, заводится перед первым
     * прогоном, а @load заполняет её, как арену. */
    SmpView   views[SMP_MAX_VIEWS];
    uint32_t  n_views;
    uint8_t  *view_mem;

    /* Рабочая память ядер — своя у каждого инстанса. Именно она делает
     * несколько VM в разных потоках безопасными. */
    void        *scratch_mem;
    size_t       scratch_bytes;
    SmpKScratch  scratch;
} SmpVM;

SmpStatus smp_vm_init(SmpVM *vm, const SmpModule *mod, SmpDiagCtx *diag);

/* То же, но с явным числом потоков для крупного GEMM: под каждый поток —
 * свой комплект рабочей памяти. smp_vm_init берёт по числу процессоров;
 * пул поднимает инстансы с par = 1 — они и так раскиданы по потокам, и
 * параллелизм внутри параллелизма дал бы только лишнюю память. */
SmpStatus smp_vm_init_ex(SmpVM *vm, const SmpModule *mod, SmpDiagCtx *diag,
                         uint32_t par);

/* Подключить привязки. Зовётся между init и run; без неё @load и @store
 * честно падают с E0606, а не читают что попало. */
void      smp_vm_bind(SmpVM *vm, const SmpBind *binds, uint32_t n);

/* Подключить хранилище. Тоже между init и run; с ним привязки к файлам не
 * используются вовсе. */
void      smp_vm_store(SmpVM *vm, const SmpStore *store);
SmpStatus smp_vm_run(SmpVM *vm);
void      smp_vm_release(SmpVM *vm);

/* Дамп регистров — тот самый, который спецификация обещает при фатальной
 * ошибке. Подходит под SmpRegDumpFn и ставится в диагностический контекст. */
void      smp_vm_regdump(SmpDiagCtx *d, void *vm, bool color);

/* Где лежат байты тензора: в арене, по адресу вида или в копии видов. NULL —
 * негде (вид, который на этом прогоне ещё не загружали). Без проверок границ
 * и без диагностики: для дампа и для хозяина после прогона. */
const void *smp_vm_tensor_data(const SmpVM *vm, const SmpTensor *t);

/* Показать содержимое именованных тензоров после прогона. */
void      smp_vm_dump_tensors(FILE *out, const SmpVM *vm, uint32_t max_elems);

/* Вывод тензора в поток. Живёт отдельным файлом: к диспетчеризации отношения
 * не имеет, а вот к философии — прямое. */
SmpStatus smp_vm_emit(FILE *dst, SmpLog *log, const struct SmpBuf *src,
                      uint8_t fmt, uint64_t *n_written, uint32_t *bad_cp);

/* Строка «какая ветка ядер выбрана» — для отчётов. */
const char *smp_vm_backend(void);

#endif /* SMPC3_VM_H */
