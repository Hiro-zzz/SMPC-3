/* SMPC3 :: diag_codes.h -- реестр диагностических кодов.
 *
 * Единственный источник правды. X-макрос разворачивается в enum, в таблицу
 * описаний и в справочник для CLI (`smpc3 explain E0418`).
 *
 *   X(ident, text, severity, category, title, fix, diagnosis)
 *
 * diagnosis — собственная строка ДИАГНОЗ для этого кода. NULL означает
 * «взять из пула категории»: пул даёт разнообразие, но говорит общо, и на
 * кодах, где точность важнее, она проигрывает. Своя строка перебивает пул.
 *
 * Диапазоны:
 *   E01xx  лексер          E04xx  память / формы / указатели
 *   E02xx  парсер          E05xx  SIMD / ISA
 *   E03xx  типы            E06xx  рантайм
 *   E09xx  внутренние      W0xxx  предупреждения
 */
