/* SMPC3 :: fmath.h -- свои exp, log, sin, cos.
 *
 * Не libm, потому что у хозяина её может не быть (в ядре NablaOS её нет), а
 * главное — потому что у разных libm разные последние биты. Одна и та же
 * программа обязана давать одни и те же числа везде, где собран SMPC3; для
 * этого функции свои и считаются только сложениями и умножениями double.
 *
 * Точность — пара ulp double на всей области, которая нужна языку. Этого с
 * запасом хватает, чтобы результат, приведённый к f32, был правильно
 * округлённым почти всегда.
 */
#ifndef SMPC3_FMATH_H
#define SMPC3_FMATH_H

#include "smpc3/common.h"

double smp_exp(double x);

/* x <= 0 даёт -inf (для нуля) или NaN. */
double smp_log(double x);

/* Приведение к [-pi/4, pi/4] точно для |x| до ~8e5; дальше точность
 * постепенно падает. Углам RoPE (позиция до 32768) этого хватает. */
void   smp_sincos(double x, double *s, double *c);

/* Корень — одна инструкция SSE2, но вызов libm не годится и здесь. */
double smp_sqrt(double x);

#endif /* SMPC3_FMATH_H */
