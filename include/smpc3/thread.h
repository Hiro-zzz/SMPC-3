/* SMPC3 :: thread.h -- минимальная обвязка над потоками ОС.
 *
 * Здесь ровно то, что нужно пулу инстансов, и ни строчкой больше: запустить N
 * потоков, дождаться всех, разделить между ними работу атомарным счётчиком.
 * Ни мьютексов, ни условных переменных, ни пулов-внутри-пула — инстансы по
 * построению не разделяют ничего, кроме этого счётчика.
 */
#ifndef SMPC3_THREAD_H
#define SMPC3_THREAD_H

#include "smpc3/common.h"

/* Тело потока: ctx общий, idx — номер потока от 0 до n-1. */
typedef void (*SmpThreadFn)(void *ctx, uint32_t idx);

/* Запускает n потоков и возвращается, когда все завершились. При n <= 1
 * выполняет всё в текущем потоке, не трогая ОС. */
SmpStatus smp_threads_run(SmpThreadFn fn, void *ctx, uint32_t n);

/* Атомарный инкремент. Возвращает значение ДО increment (fetch_add). */
int32_t   smp_atomic_fetch_add(volatile int32_t *p, int32_t v);

/* Прибить текущий поток к одному логическому процессору и отпустить обратно.
 *
 * Нужно замерам, а не рантайму. У гибридных процессоров (P- и E-ядра) поток
 * закрепляется за ядром один раз и сидит там весь прогон: попал на E-ядро —
 * и AVX2 идёт впятеро медленнее, причём стабильно, так что повторные проходы
 * этого не сглаживают. Без закрепления число «ГФЛОПС на ядро» не значит
 * ничего: неизвестно, на каком оно ядре.
 *
 * Возвращает false, если ОС отказала; замер тогда честнее пометить. */
bool smp_thread_pin(uint32_t cpu);
void smp_thread_unpin(void);

/* Сколько потоков имеет смысл поднимать по умолчанию. */
uint32_t  smp_threads_default(void);

#endif /* SMPC3_THREAD_H */
