/* SMPC3 :: plat.h -- всё, что язык просит у операционной системы.
 *
 * Компилятор, VM и ядра от ОС не зависят. Всё, где зависимость неизбежна —
 * страницы под арены, потоки, часы, окружение, консоль, — собрано здесь, в
 * одном интерфейсе. Реализаций две:
 *
 *   src/plat/host.c   Windows и POSIX; с ней собираются smpc3.exe и тесты;
 *   ядро NablaOS      своя, в дереве ядра: страницы из PMM, часы из TSC,
 *                     потоки — ядра процессора.
 *
 * Чего здесь нет — файлов. Исходники, .s3b и привязки @load/@store читаются
 * через stdio. Там, где файлов нет вовсе, fopen просто не открывает ничего,
 * и язык отвечает на это своей обычной диагностикой, а не падением.
 */
#ifndef SMPC3_PLAT_H
#define SMPC3_PLAT_H

#include <stdio.h>

#include "smpc3/common.h"
#include "smpc3/thread.h"

/* --- Память --------------------------------------------------------------
 *
 * Единственный источник памяти во всём проекте. Блок обнулён и выровнен как
 * минимум на 4096 байт; NULL — если ОС отказала. Зовётся только при подъёме:
 * арены, рабочая память ядер, служебные таблицы пула. На исполнении — никогда.
 *
 * Освобождение принимает тот же размер, что просили: страничным аллокаторам
 * он нужен, а вызывающий его всё равно знает. */
void       *smp_plat_pages(size_t bytes);
void        smp_plat_pages_free(void *p, size_t bytes);

/* --- Процессоры и потоки ------------------------------------------------- */

uint32_t    smp_plat_cpus(void);

/* Запустить fn(ctx, i) для i = 0..n-1 параллельно и вернуться, когда все
 * закончили. Если часть потоков не поднялась, их долю выполняет вызывающий
 * поток, а результат — SMP_ERR_INTERNAL: работа сделана, но не так, как
 * просили. n уже проверено вызывающим (2..64). */
SmpStatus   smp_plat_threads(SmpThreadFn fn, void *ctx, uint32_t n);

/* Закрепить текущий поток за логическим процессором и отпустить. Нужно
 * замерам; false — ОС не дала, и замер честнее пометить. */
bool        smp_plat_pin(uint32_t cpu);
void        smp_plat_unpin(void);

/* --- Время и окружение --------------------------------------------------- */

/* Монотонные секунды от произвольной точки отсчёта. */
double      smp_plat_seconds(void);

/* Значение переменной окружения или NULL. Через неё подменяются ширина
 * вектора и блокировка GEMM — чтобы воспроизвести чужой отчёт. */
const char *smp_plat_env(const char *name);

/* --- Консоль ------------------------------------------------------------- */

/* Подготовить консоль к UTF-8 и цвету; зовётся один раз на старте. */
void        smp_plat_console_setup(void);

/* Терминал ли это — от этого зависит, красить ли диагностику. */
bool        smp_plat_isatty(FILE *f);

#endif /* SMPC3_PLAT_H */
